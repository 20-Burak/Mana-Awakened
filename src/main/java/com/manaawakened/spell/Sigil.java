    /** How a sigil resolves. */
    public enum Kind {
        /** A ray along the view line. */
        BEAM,
        /** A bolt dropped on the spot looked at. */
        STRIKE,
        /** Absorption around the caster. */
        WARD,
        /** Healing around the caster. */
        RESTORE,
        /** A teleport along the view line. */
        BLINK,
        /** A burst around the caster. */
        NOVA,
        /** A delayed impact at the spot looked at. */
        METEOR,
        /** A column that erupts at the spot looked at. */
        PILLAR,
        /** A cone in front of the caster. */
        CONE,
        /** A shockwave rolling forward along the ground. */
        WAVE,
        /** Seeking projectiles. */
        BARRAGE,
        /** An area under a storm for some seconds. */
        RAIN,
        /** A lingering whirl that drags in and wears down. */
        VORTEX,
        /** A lingering zone that mends allies. */
        SANCTUARY,
        /** Long-lasting boons for the caster and allies. */
        BUFF,
        /** Debuffs on the foes of an area. */
        CURSE,
        /** A rush forward that strikes what it passes. */
        DASH,
        /** A working spell, see {@link Rite}. */
        UTILITY;

        /** Kinds that hurt creatures (as opposed to ward, restore, blink, buff and sanctuary). */
        public boolean damaging() {
            return switch (this) {
                case WARD, RESTORE, BLINK, SANCTUARY, BUFF, UTILITY -> false;
                default -> true;
            };
        }

        /** Kinds that act where the caster looks and so draw their circle at the target. */
        public boolean atTarget() {
            return switch (this) {
                case STRIKE, METEOR, PILLAR, RAIN, VORTEX, CURSE, NOVA -> true;
                default -> false;
            };
        }

        /** Kinds whose circle lies under the caster's feet. */
        public boolean aroundCaster() {
            return switch (this) {
                case WARD, RESTORE, NOVA, SANCTUARY, BUFF -> true;
                default -> false;
            };
        }
    }

