    Sigil(String id, int minCircle, Kind kind, Element element, double baseCost, int baseCooldown, double basePower, double baseRange,
          double baseRadius, int ringSize, int color, int variant, String innateLevels, Rite rite) {
        this.id = id;
        this.minCircle = minCircle;
        this.kind = kind;
        this.element = element;
        this.baseCost = baseCost;
        this.baseCooldown = baseCooldown;
        this.basePower = basePower;
        this.baseRange = baseRange;
        this.baseRadius = baseRadius;
        this.ringSize = ringSize;
        this.color = color;
        this.variant = variant;
        this.rite = rite;
        if ((kind == Kind.UTILITY) != (rite != Rite.NONE)) {
            throw new IllegalStateException("Sigil " + id + ": a utility sigil needs a rite, and only a utility sigil has one");
        }
        EnumSet<Modifier> allowed = EnumSet.copyOf(modifiersFor(kind, rite));
        if (canDestroy()) {
            allowed.add(Modifier.DEVASTATION);
        } else {
            allowed.remove(Modifier.DEVASTATION);
        }
        this.modifiers = allowed;
        for (String entry : innateLevels.split(",")) {
            int colon = entry.indexOf(':');
            if (colon > 0) {
                Modifier modifier = Modifier.byId(entry.substring(0, colon).toLowerCase(Locale.ROOT));
                if (modifier != null) {
                    innate[modifier.ordinal()] = Integer.parseInt(entry.substring(colon + 1));
                }
            }
        }
    }

    private static Set<Modifier> modifiersFor(Kind kind, Rite rite) {
        EnumSet<Modifier> common = EnumSet.of(Modifier.POWER, Modifier.QUICKEN, Modifier.EFFICIENCY, Modifier.ECHO);
        return switch (kind) {
            case BEAM -> EnumSet.allOf(Modifier.class);
            case STRIKE -> with(common, Modifier.RANGE, Modifier.MULTI, Modifier.CHAIN, Modifier.RADIUS, Modifier.LEECH, Modifier.KNOCKBACK,
                    Modifier.IGNITE, Modifier.FROSTBITE);
            case WARD -> EnumSet.of(Modifier.POWER, Modifier.LINGER, Modifier.RADIUS, Modifier.QUICKEN, Modifier.EFFICIENCY);
            case RESTORE -> EnumSet.of(Modifier.POWER, Modifier.LINGER, Modifier.RADIUS, Modifier.QUICKEN, Modifier.EFFICIENCY, Modifier.ECHO);
            case BLINK -> EnumSet.of(Modifier.RANGE, Modifier.QUICKEN, Modifier.EFFICIENCY, Modifier.ECHO);
            case NOVA -> with(common, Modifier.RANGE, Modifier.RADIUS, Modifier.LEECH, Modifier.KNOCKBACK, Modifier.IGNITE, Modifier.FROSTBITE, Modifier.LINGER);
            case METEOR -> with(common, Modifier.RANGE, Modifier.MULTI, Modifier.RADIUS, Modifier.LEECH, Modifier.KNOCKBACK, Modifier.IGNITE,
                    Modifier.FROSTBITE);
            case PILLAR -> with(common, Modifier.RANGE, Modifier.MULTI, Modifier.CHAIN, Modifier.RADIUS, Modifier.LINGER, Modifier.LEECH,
                    Modifier.KNOCKBACK, Modifier.IGNITE, Modifier.FROSTBITE);
            case CONE -> with(common, Modifier.RANGE, Modifier.RADIUS, Modifier.LINGER, Modifier.LEECH, Modifier.KNOCKBACK, Modifier.IGNITE,
                    Modifier.FROSTBITE);
            case WAVE -> with(common, Modifier.RANGE, Modifier.MULTI, Modifier.RADIUS, Modifier.LINGER, Modifier.LEECH, Modifier.KNOCKBACK,
                    Modifier.IGNITE, Modifier.FROSTBITE);
            case BARRAGE -> with(common, Modifier.RANGE, Modifier.MULTI, Modifier.PIERCE, Modifier.CHAIN, Modifier.RADIUS, Modifier.LEECH,
                    Modifier.KNOCKBACK, Modifier.IGNITE, Modifier.FROSTBITE);
            case RAIN -> with(common, Modifier.RANGE, Modifier.MULTI, Modifier.RADIUS, Modifier.LINGER, Modifier.LEECH, Modifier.KNOCKBACK,
                    Modifier.IGNITE, Modifier.FROSTBITE);
            case VORTEX -> with(common, Modifier.RANGE, Modifier.RADIUS, Modifier.LINGER, Modifier.LEECH, Modifier.KNOCKBACK, Modifier.IGNITE,
                    Modifier.FROSTBITE);
            case SANCTUARY -> EnumSet.of(Modifier.POWER, Modifier.LINGER, Modifier.RADIUS, Modifier.QUICKEN, Modifier.EFFICIENCY, Modifier.ECHO);
            case BUFF -> EnumSet.of(Modifier.POWER, Modifier.LINGER, Modifier.RADIUS, Modifier.QUICKEN, Modifier.EFFICIENCY);
            case CURSE -> with(common, Modifier.RANGE, Modifier.RADIUS, Modifier.LINGER, Modifier.LEECH, Modifier.IGNITE, Modifier.FROSTBITE);
            case DASH -> with(common, Modifier.RANGE, Modifier.PIERCE, Modifier.RADIUS, Modifier.LEECH, Modifier.KNOCKBACK, Modifier.IGNITE,
                    Modifier.FROSTBITE);
            case UTILITY -> {
                EnumSet<Modifier> set = EnumSet.of(Modifier.QUICKEN, Modifier.EFFICIENCY);
                set.addAll(rite.modifiers());
                yield set;
            }
        };
    }

    private static Set<Modifier> with(EnumSet<Modifier> base, Modifier... more) {
        EnumSet<Modifier> set = EnumSet.copyOf(base);
        for (Modifier modifier : more) {
            set.add(modifier);
        }
        return set;
    }

