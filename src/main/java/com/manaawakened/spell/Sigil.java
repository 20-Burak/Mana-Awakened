    /** The sigil with this id; an id retired in 3.0.0 gives the sigil that replaced it. */
    public static @Nullable Sigil byId(String id) {
        for (Sigil sigil : VALUES) {
            if (sigil.id.equals(id)) {
                return sigil;
            }
        }
        String replacement = RETIRED.get(id);
        return replacement == null ? null : byId(replacement);
    }

